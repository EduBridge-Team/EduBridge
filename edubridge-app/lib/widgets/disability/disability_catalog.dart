// ═══════════════════════════════════════════════════════════
//  قائمة مسطّحة لكل الإعاقات (للاستخدام السريع)
// ═══════════════════════════════════════════════════════════
List<String> get kAllDisabilityTypes {
  final all = <String>[];
  for (final cat in kDisabilityCategories) {
    all.addAll(cat.items);
  }
  all.add('بدون تكييف');
  all.add('أخرى');
  return all;
}

// ═══════════════════════════════════════════════════════════
//  ربط الإعاقة المُصنّفة بنوع التكييف (DisabilityType)
// ═══════════════════════════════════════════════════════════
DisabilityType disabilityTypeForCategory(String disability) {
  final d = disability.trim();

  // ═══ البصرية ═══
  if (d == 'عمى الألوان') {
    return DisabilityType.colorBlindness;
  }
  if (d == 'شبه كفيف' ||
      d == 'كفيف كلي' ||
      d == 'فقد عين واحدة') {
    return DisabilityType.blind;
  }

  // ═══ السمعية ═══
  if (d.startsWith('ضعف سمع') ||
      d == 'أصم' ||
      d == 'زارعي القوقعة') {
    return DisabilityType.deaf;
  }

  // ═══ النطق واللغة ═══
  if (d == 'تأتأة') {
    return DisabilityType.stuttering;
  }
  if (d == 'تأخر اللغة الاستيعابية' ||
      d == 'تأخر اللغة التعبيرية' ||
      d == 'الحبسة الكلامية' ||
      d == 'تأخر النطق' ||
      d == 'تأخر في الكلام والنطق واللغة') {
    return DisabilityType.speechDisorders;
  }

  // ═══ الحركية والشلل ═══
  if (d.startsWith('شلل') ||
      d == 'استسقاء الحبل الشوكي' ||
      d == 'إصابات الحبل الشوكي' ||
      d == 'العظم الزجاجي') {
    return DisabilityType.motorDisability;
  }

  // ═══ الدماغ ═══
  if (d == 'أمراض عصبية' || d == 'إصابات دماغ' || d == 'الصرع') {
    return DisabilityType.epilepsy;
  }
  if (d == 'ضمور في الدماغ') {
    return DisabilityType.mildIntellectual;
  }

  // ═══ النمائية والسلوكية ═══
  if (d == 'طيف التوحّد (بسيط/متوسط)') {
    return DisabilityType.autismMild;
  }
  if (d == 'طيف التوحّد (شديد)') {
    return DisabilityType.autismSevere;
  }
  if (d == 'فرط الحركة وتشتت الانتباه') {
    return DisabilityType.adhd;
  }
  if (d == 'اضطرابات سلوك الأطفال') {
    return DisabilityType.adhd;
  }
  if (d == 'اضطرابات فصام الشخصية' ||
      d == 'اضطرابات عصاب التحول') {
    return DisabilityType.other;
  }

  // ═══ الذهنية وصعوبات التعلم ═══
  if (d.startsWith('صعوبة تعلم') ||
      d.startsWith('تخلف عقلي')) {
    return DisabilityType.mildIntellectual;
  }
  if (d == 'متلازمة داون') {
    return DisabilityType.downSyndrome;
  }

  // ═══ خاص ═══
  if (d == 'بدون تكييف') {
    return DisabilityType.none;
  }
  if (d == 'أخرى') {
    return DisabilityType.other;
  }

  // ═══ افتراضي ═══
  return DisabilityType.other;
}

// ═══════════════════════════════════════════════════════════
//  هل هذه الإعاقة معروفة في الكتالوج؟
// ═══════════════════════════════════════════════════════════
bool isKnownDisability(String disability) {
  return kAllDisabilityTypes.contains(disability.trim());
}

// ═══════════════════════════════════════════════════════════
//  الحصول على إيموجي الإعاقة
// ═══════════════════════════════════════════════════════════
String disabilityEmojiFor(String disability) {
  final type = disabilityTypeForCategory(disability);
  return disabilityEmojis[type] ?? '⚪';
}

// ═══════════════════════════════════════════════════════════
//  الحصول على التسمية العربية المُصنّفة لإعاقة
// ═══════════════════════════════════════════════════════════
String disabilityLabelFor(String disability) {
  final type = disabilityTypeForCategory(disability);
  return disabilityLabels[type] ?? disability;
